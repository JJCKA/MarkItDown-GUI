"""Built-in prompt templates for LLM-powered content analysis."""

# ==============================================================================
# 系统级强制指令：禁止 LLM 输出任何对话性废话
# ==============================================================================
SYSTEM_PROMPT_STRICT = (
    "你是一个无情的、专业的文档处理引擎。你必须直接输出分析结果或清洗后的内容，"
    "绝对不允许包含任何前置问候语、后置解释语、或诸如'好的'、'作为助手'之类的对话性废话。"
    "直接给结果！"
)

# ==============================================================================
# 图片描述（内联用，简短直接）
# ==============================================================================
IMAGE_PROMPT = """请用 Markdown 直接描述这张图片的内容，不要输出图片本身的标题（标题由程序生成）。
如果图片中有文字，请完整提取。
子标题使用 #### 级别。不要输出任何对话性废话。"""

IMAGE_OCR_PROMPT = """请识别并提取这张图片中的所有文字，用 Markdown 格式输出，保持排版结构。"""

# ==============================================================================
# 音频转录
# ==============================================================================
AUDIO_PROMPT = """请将以下音频内容转录为文字，保持原始语言，用 Markdown 格式输出。"""

# ==============================================================================
# 文档摘要分析（启用"全文内容总结"时使用）
# ==============================================================================
DOCUMENT_SUMMARY_PROMPT = """请对以下文档进行分析，输出：
1. **核心主题**
2. **关键要点**（3-5 个）
3. **结构分析**
用 Markdown 格式输出。"""

# ==============================================================================
# 复杂表单清洗（启用"表单清洗"时使用）
# ==============================================================================
FORM_CLEANING_PROMPT = """你是一个专业的文档排版专家。用户会输入一段由机器提取的、格式混乱的 Markdown 文本（通常是从带有复杂排版表格的 Word/PDF 中提取的）。
你的任务是将这些"为了排版而滥用的表格"展平，转换为结构清晰的普通 Markdown 文档。

【转换规则】：
1. 提取键值对：将表格中的表头和内容，转换为"**字段名**：内容"的格式。
2. 释放长文本：如果发现单元格内包含大段描述文本（如"项目摘要"、"主要内容"），请将其从表格中提取出来，变成独立的段落。
3. 保留真实表格：如果遇到真正的"数据统计表"（如财务明细、人员清单，且没有复杂的合并单元格），请保留 Markdown 表格格式。
4. 修复层级：根据内容逻辑，合理使用 Markdown 的一、二、三级标题 (###) 和列表 (-)。
5. 保持内容完整：绝对不允许删减用户的任何业务数据和原始文字。

直接输出清洗后的 Markdown 内容，绝对不允许包含任何额外的解释性对话！"""

# ==============================================================================
# 数据分析 / 代码分析（备用 prompt）
# ==============================================================================
TABLE_PROMPT = """请分析以下数据内容，输出数据概览、关键发现和建议。用 Markdown 格式。"""

CODE_PROMPT = """请分析以下代码，输出语言识别、功能概述、关键逻辑和改进建议。用 Markdown 格式。"""

# ==============================================================================
# Prompt 注册表
# ==============================================================================
PROMPTS = {
    "image": {"name": "图像描述", "prompt": IMAGE_PROMPT},
    "image_ocr": {"name": "图片文字识别 (OCR)", "prompt": IMAGE_OCR_PROMPT},
    "audio": {"name": "音频转录", "prompt": AUDIO_PROMPT},
    "document_summary": {"name": "文档摘要分析", "prompt": DOCUMENT_SUMMARY_PROMPT},
    "form_cleaning": {"name": "复杂表单清洗", "prompt": FORM_CLEANING_PROMPT},
    "table": {"name": "数据分析", "prompt": TABLE_PROMPT},
    "code": {"name": "代码分析", "prompt": CODE_PROMPT},
}

# ==============================================================================
# 文件扩展名分类
# ==============================================================================
IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".gif", ".bmp", ".webp", ".svg", ".tiff"}
AUDIO_EXTENSIONS = {".mp3", ".wav", ".flac", ".aac", ".ogg", ".m4a", ".wma"}
TABLE_EXTENSIONS = {".csv", ".xlsx", ".xls", ".json", ".xml", ".yaml", ".yml"}
CODE_EXTENSIONS = {".py", ".js", ".ts", ".java", ".c", ".cpp", ".h", ".go", ".rs", ".rb", ".php"}
DOCUMENT_EXTENSIONS = {".docx", ".doc", ".pptx", ".ppt", ".pdf", ".odt", ".odp", ".ods", ".epub"}


def get_prompt_for_file(file_ext: str) -> dict | None:
    ext = file_ext.lower()
    if ext in IMAGE_EXTENSIONS:
        return PROMPTS["image"]
    elif ext in AUDIO_EXTENSIONS:
        return PROMPTS["audio"]
    elif ext in TABLE_EXTENSIONS:
        return PROMPTS["table"]
    elif ext in CODE_EXTENSIONS:
        return PROMPTS["code"]
    return None
